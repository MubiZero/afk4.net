namespace AFK4.Platform.Api.Tests;

/// <summary>
/// Телефон для сида игрока — уникальный по построению, а не по удаче.
///
/// Раньше каждый файл сочинял номер сам, из хеша случайного Guid: `+99290000{hash % 10_000}`.
/// Пространство четырёхзначное, игроков в одном тесте бывает трое, а префиксы у половины файлов
/// совпадали — рано или поздно двое получали один номер. Дальше цепочка: in-memory провайдер
/// уникальный индекс по телефону не исполняет, в `platform_persons` ложатся две строки с одним
/// номером, а вход по PIN ищет личность через `SingleOrDefault` и отвечает пятисоткой.
///
/// Хуже всего было то, что локально это не воспроизводилось никогда: Guid каждый раз новые.
/// Падало только на CI и только у того, кто ни при чём.
///
/// Счётчик один на весь прогон, поэтому номера не сталкиваются ни внутри файла, ни между файлами.
/// </summary>
internal static class TestPhones
{
    private static int counter;

    /// <summary>Следующий свободный номер в форме `+992 9XXXXXXXX` — та же, что у живых номеров.</summary>
    public static string Next() => $"+9929{Interlocked.Increment(ref counter):D8}";
}
