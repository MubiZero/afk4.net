/**
 * Минимальная длина пароля сотрудника.
 *
 * Правило живёт на сервере (`EndpointHelpers.ValidateStaffPassword`), а экраны проверяют то же
 * самое до отправки, чтобы не гонять человека до сервера ради заведомого отказа. Раньше число
 * было выписано в четырёх экранах и в пяти строках каталога: чтобы его изменить, надо было
 * вспомнить все девять мест. Теперь оно одно, а совпадение с сервером стережёт passwordPolicy.test.ts.
 */
export const MIN_STAFF_PASSWORD_LENGTH = 4;

/**
 * Минимальная длина пароля администратора платформы.
 *
 * Своё число, и оно осталось прежним: за этой дверью вся сеть клубов — заведение организаций,
 * деньги и права всех сотрудников. Экран активации один на две роли, поэтому число он выбирает
 * по роли, а не берёт одно на обе.
 */
export const MIN_PLATFORM_ADMIN_PASSWORD_LENGTH = 8;
