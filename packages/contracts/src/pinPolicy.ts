/**
 * Форма ПИН-кода — ровно шесть цифр, и это единственное правило входа во всей системе: им садится
 * за ПК гость, им же входят сотрудник клуба, владелец и администратор платформы.
 *
 * Правило живёт на сервере (`PinFormat` в `Identity/PinContracts.cs`), а экраны проверяют то же
 * самое до отправки, чтобы не гонять человека до сервера ради заведомого отказа. Совпадение
 * сторожит pinPolicy.test.ts: экран, который требует больше сервера, зря не пускает; экран,
 * который требует меньше, отправляет за отказом.
 */
export const PIN_LENGTH = 6;

/** Ровно шесть цифр и ничего кроме: то же, что проверит сервер. */
export const isWellFormedPin = (value: string): boolean =>
  value.length === PIN_LENGTH && [...value].every((character) => character >= '0' && character <= '9');

/**
 * Что оставить от набранного в поле ПИН-кода.
 *
 * Поле не ругается на лишнее, а просто его не принимает: буква, пробел и вставленный из буфера
 * старый пароль отсеиваются на лету, а после шестой цифры ввод останавливается. Цифры именно
 * ASCII — арабо-индийские выглядят как цифры, но второй раз на другой раскладке их не набрать.
 */
export const keepPinDigits = (value: string): string =>
  [...value]
    .filter((character) => character >= '0' && character <= '9')
    .slice(0, PIN_LENGTH)
    .join('');
