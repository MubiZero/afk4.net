import { useId } from 'react';

/**
 * Почему кнопка или поле неактивны — словами, рядом с ними.
 *
 * Серая кнопка без объяснения заставляет гадать: нет смены? нет права? не выбрано место?
 * Всплывающая подсказка не спасает — на неактивной кнопке браузер её не показывает, а на
 * сенсорном экране её нет вовсе. Поэтому причина — обычный текст, а элемент ссылается на него
 * через `aria-describedby`, чтобы экранный диктор прочитал её вместе с ним.
 *
 * Причина нужна, когда элемент гасит условие или право, которого на экране не видно. Пока идёт
 * запрос или пустое поле стоит прямо над кнопкой, объяснять нечего.
 */
export function useBlockedReason(reason: string | null) {
  const id = useId();
  return {
    describedBy: reason === null ? undefined : id,
    hint: reason === null ? null : <p id={id} className="ui-blocked-reason" role="status">{reason}</p>,
  };
}
