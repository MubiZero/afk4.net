namespace AFK4.Shared.Contracts.Tariffs;

/// <summary>
/// Когда действует тариф: дни недели и окно местного времени филиала.
///
/// <c>AppliesOnDaysMask</c> — биты с понедельника (1) по воскресенье (64); <c>0</c> означает
/// «каждый день». Часы — минуты от полуночи; оба <c>null</c> означают «круглые сутки», а начало
/// больше конца — окно через полночь.
///
/// Расписание вынесено отдельным объектом намеренно. В запросе на изменение тарифа плоские поля
/// со значениями по умолчанию означали бы, что вызывающий, не знающий про расписание, стирает его
/// молча: PATCH, у которого пропущенное поле уничтожает данные, — ловушка. Здесь <c>null</c> у
/// всего объекта означает «не трогать», и не знать про расписание безопасно.
/// </summary>
public sealed record TariffScheduleDto(
    int AppliesOnDaysMask = 0,
    int? AppliesFromMinuteOfDay = null,
    int? AppliesToMinuteOfDay = null);
