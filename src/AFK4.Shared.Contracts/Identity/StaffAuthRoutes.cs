namespace AFK4.Shared.Contracts.Identity;

/// <summary>
/// Пути входа сотрудника **до** того, как известна организация. По той же причине, что
/// <see cref="Install.InstallRoutes"/> и <see cref="StaffRoutes"/>: строка, живущая в двух
/// местах, однажды уже развела мастер и сервер.
///
/// Здесь она разводила их прямо сейчас: мастер слал на эти корневые адреса, а сервер отвечал
/// только под <c>/api/organizations/{id}/auth/staff/*</c>. Обе стороны были покрыты зелёными
/// тестами — каждая проверяла себя, — а на живом API мастер получал 404 на первом же экране.
///
/// Почему корень, а не канонический префикс организации: мастер ставит первый ПК в клубе и
/// узнаёт организацию **из ответа на вход**. Требовать её в пути — значит требовать знать
/// ответ до вопроса. Тот же довод уже принят для сброса пароля
/// (<c>/api/auth/staff/forgot-password*</c>), который живёт в корне с самого начала.
///
/// Организационные копии этих маршрутов остаются: их знают установленные в поле сборки
/// Organization Admin, которые организацию как раз знают — она записана на машине.
/// </summary>
public static class StaffAuthRoutes
{
    /// <summary>Вход в названную организацию: она приходит в теле запроса.</summary>
    public const string SignIn = "/api/auth/staff/sign-in";

    /// <summary>
    /// Вход по логину или почте без организации. Один ответ — токен; несколько — 409 со списком
    /// клубов, из которого человек выбирает и возвращается сюда через <see cref="SignIn"/>.
    /// </summary>
    public const string SignInByLogin = "/api/auth/staff/sign-in-by-login";

    /// <summary>
    /// Вход по подтверждённому телефону. Номер уникален по сети, поэтому организация выводится
    /// из него самого и в пути не нужна.
    /// </summary>
    public const string SignInByPhone = "/api/auth/staff/sign-in-by-phone";

    /// <summary>
    /// Первый шаг входа по номеру: что спросить дальше — ПИН или код первого входа. Номер уникален
    /// по сети, поэтому организация не нужна и здесь.
    /// </summary>
    public const string NextStep = "/api/auth/staff/next-step";

    /// <summary>Проверить код первого входа, не принимая приглашение.</summary>
    public const string CheckInvite = "/api/staff/invites/check";

    /// <summary>Принять приглашение: код первого входа и новый ПИН. Ответ сразу несёт вход.</summary>
    public const string AcceptInvite = "/api/staff/invites/accept";
}
