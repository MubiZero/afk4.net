import 'dart:math';

/// Ключ идемпотентности для денежных действий.
///
/// Нужен там, где повтор запроса означает второе списание: ответ потерялся в пути, игрок
/// нажал ещё раз — сервер по ключу узнаёт ту же попытку и не берёт деньги дважды. Поэтому
/// ключ генерируется ОДИН раз на попытку и переиспользуется при повторе, а не на каждый вызов.
String newIdempotencyKey() {
  final stamp = DateTime.now().microsecondsSinceEpoch.toRadixString(36);
  // Потолок ровно в 2^31-1, а не 1 << 32: у `nextInt` верхняя граница платформозависима, и
  // на вебе значение с краю диапазона роняет генератор. В тестах на виртуальной машине это
  // не видно — ловится только живым прогоном в браузере.
  final noise = _random.nextInt(0x7fffffff).toRadixString(36);
  return '$stamp-$noise';
}

final Random _random = Random();

/// Ключ одной попытки денежного действия.
///
/// Живёт столько же, сколько сама попытка: неудача его НЕ сбрасывает. Повтор после обрыва
/// обязан прийти с тем же ключом — только по нему сервер узнаёт, что это та же покупка, а не
/// вторая, и не берёт деньги дважды. Новый ключ на каждое нажатие делает всю защиту
/// бессмысленной ровно в том случае, ради которого она написана.
class AttemptKey {
  String? _key;
  String? _subject;

  /// Ключ текущей попытки. `subject` описывает, что покупают: сменился — значит попытка
  /// другая и ключ ей нужен свой, иначе сервер ответит конфликтом «тот же ключ с другим телом».
  String forSubject(String subject) {
    if (_subject != subject) {
      _subject = subject;
      _key = null;
    }
    return _key ??= newIdempotencyKey();
  }

  /// Попытка кончилась — успехом или отказом, который повтором не лечится. Следующая такая же
  /// покупка обязана нести новый ключ: со старым сервер вернул бы ответ прошлой и денег не взял.
  void done() {
    _key = null;
    _subject = null;
  }
}
