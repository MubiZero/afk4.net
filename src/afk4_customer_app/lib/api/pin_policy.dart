/// Форма ПИН-кода — ровно шесть цифр, и это единственное правило входа во всей системе: им
/// садится за ПК гость, им же входят сотрудник клуба, владелец и администратор платформы.
///
/// Правило живёт на сервере (`PinFormat` в `Identity/PinContracts.cs`); здесь оно продублировано,
/// потому что генератор контрактов переносит записи, а не статические классы. Совпадение сторожит
/// `test/pin_policy_test.dart`: две проверки одной длины разъехались бы на первой правке.
class PinPolicy {
  const PinPolicy._();

  static const int length = 6;

  /// Ровно шесть цифр и ничего кроме — то же, что проверит сервер. Цифры именно ASCII:
  /// арабо-индийские выглядят цифрами, но второй раз на другой раскладке их не набрать.
  static bool isWellFormed(String pin) =>
      pin.length == length &&
      pin.codeUnits.every((unit) => unit >= 0x30 && unit <= 0x39);
}
