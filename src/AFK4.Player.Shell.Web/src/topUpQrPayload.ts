import type { PlayerTopUpIntentDto } from '@afk4/contracts';

/**
 * Что кодировать в QR на экране пополнения.
 *
 * Оболочка живёт на игровом ПК: человек наводит на экран телефон, и от того, что зашито в код,
 * зависит, куда он попадёт.
 *
 * — `qr` выдаёт сам банк. Это его собственная полезная нагрузка, и банковское приложение узнаёт
 *   её как платёж. Сервер её хранит и отдаёт с самого начала, а экран её не читал вовсе и рисовал
 *   код из `payUrl` — то есть из веб-страницы счёта. Камера такой код откроет в браузере, а
 *   банковское приложение может не узнать вовсе.
 * — `deepLink` открывает приложение банка. Годится, когда своего кода банк не дал.
 * — `payUrl` остаётся последним: страница в браузере работает всегда, но лишним шагом.
 */
export function topUpQrPayload(intent: Pick<PlayerTopUpIntentDto, 'qr' | 'deepLink' | 'payUrl'>): string | null {
  return intent.qr || intent.deepLink || intent.payUrl || null;
}
