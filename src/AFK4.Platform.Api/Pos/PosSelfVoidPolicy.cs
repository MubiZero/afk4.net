using AFK4.Platform.Api.Data;

namespace AFK4.Platform.Api.Pos;

/// <summary>
/// Когда кассир может отменить СВОЙ только что пробитый чек без старшего.
///
/// Право отменять чужие и старые продажи (<c>VoidPosSale</c>) — контроль, и он остаётся: отмена
/// продажи вынимает деньги из смены, и делать это безнадзорно нельзя. Но у контроля был побочный
/// эффект: пробил не тот товар — зови старшего, даже если прошло десять секунд и покупатель ещё
/// стоит у стойки. В итоге ошибка не исправлялась, а обходилась, и расходилась не касса, а
/// история продаж.
///
/// Окно закрывает ровно бытовую опечатку и не открывает возврат наличных задним числом:
/// отменить можно свою продажу, в своей ещё не закрытой смене, в первые
/// <see cref="SelfVoidWindow"/> минут. Всё остальное по-прежнему через старшего.
/// </summary>
public static class PosSelfVoidPolicy
{
    /// <summary>
    /// Пять минут. Столько живёт «я только что ошибся»: покупатель ещё у стойки, деньги ещё не
    /// разошлись по смене. Шире — это уже не опечатка, а операция, у которой должен быть
    /// свидетель.
    /// </summary>
    public static readonly TimeSpan SelfVoidWindow = TimeSpan.FromMinutes(5);

    public static bool CanSelfVoid(
        PosSaleEntity sale,
        Guid actorStaffUserId,
        Guid? openShiftId,
        DateTimeOffset nowUtc)
    {
        // Свою — значит свою. Отменять чужой чек, пусть и свежий, кассир не может: он не знает,
        // что там пробивали.
        if (sale.CreatedByStaffUserId != actorStaffUserId)
        {
            return false;
        }

        // Смена, в которой пробили, должна быть той же и всё ещё открытой. Закрытая смена уже
        // сведена: правка задним числом ломает сверку, ради которой её и закрывали.
        if (openShiftId is null || sale.ShiftId != openShiftId)
        {
            return false;
        }

        var age = nowUtc - sale.CreatedAtUtc;

        // Отрицательный возраст — часы разъехались. В такой ситуации окно не открываем: лучше
        // отправить к старшему, чем дать бесконечное окно из-за сбитого времени.
        return age >= TimeSpan.Zero && age <= SelfVoidWindow;
    }
}
