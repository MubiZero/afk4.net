namespace AFK4.Platform.Api;

/// <summary>
/// Пределы публичных ручек «на адрес». Весь клуб — гости с телефонами на клубном Wi-Fi, касса, ПК —
/// выходит в интернет с одного адреса (NAT), поэтому предел на адрес — это предел на весь клуб, а не
/// на человека. Было 10 в минуту на всё: вечерний наплыв получал 429 на входе и продлении токенов
/// у всего зала, а вебхук банка делил то же ведро с игроками. От подбора ПИНа и пароля защищают
/// блокировки по учётной записи; здесь — только грубая защита от потока.
/// </summary>
public static class PublicRateLimits
{
    /// <summary>Вход игрока и сотрудника по номеру, доступ поддержки: попытки с паролем.</summary>
    public const int SignInPerMinute = 60;

    /// <summary>Продление и выход игрока, список клубов: обычная работа приложения у всего зала.</summary>
    public const int PlayerSessionPerMinute = 300;

    /// <summary>Регистрация: шлёт SMS за счёт клубов, поэтому строже прочих.</summary>
    public const int RegistrationPerMinute = 30;

    /// <summary>Уведомления банка: свой предел, чтобы игроки клуба не отнимали у них место.</summary>
    public const int PaymentWebhookPerMinute = 600;
}
