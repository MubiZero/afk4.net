import { useId } from 'react';

/**
 * Почему кнопка неактивна — словами, рядом с ней.
 *
 * Серая кнопка без объяснения заставляет гадать: нет смены? нет права? не выбрано место?
 * Всплывающая подсказка тут не спасает — на неактивной кнопке браузер её не показывает, а на
 * сенсорном экране её не бывает вовсе. Поэтому причина — обычный текст, а кнопка ссылается на
 * него через `aria-describedby`, чтобы экранный диктор прочитал её вместе с кнопкой.
 *
 * Причина нужна, когда кнопку гасит условие или право. Пока идёт запрос, объяснять нечего:
 * об этом говорит сама кнопка.
 */
export function useBlockedReason(reason: string | null) {
  const id = useId();
  return {
    describedBy: reason === null ? undefined : id,
    hint: reason === null ? null : <p id={id} className="ui-blocked-reason" role="status">{reason}</p>
  };
}
